(** * From Typed Terms to Cartesian Closed Categories

    The previous chapter interpreted observations as arrows into a product.
    We now give such arrows a language: simply typed lambda calculus (STLC).
    A term can pair observations, project a component, abstract an input and
    apply a function. We follow identity and duplication from syntax to
    setoid semantics, then explain the existing syntactic CCC and its
    soundness, completeness and free universal property. *)

(** * 从带类型项到笛卡尔闭范畴

    上一章把观察解释为指向积的箭头。现在为这些箭头提供一种语言：简单类型
    λ 演算（STLC）。项可以配对观察、投影分量、抽象输入并应用函数。本章用
    恒等与复制两个例子，从语法走到广集语义，再介绍已有的语法 CCC、可靠性、
    完备性与自由泛性质。 *)

