    so evaluating duplication gives the diagonal map [b] to [(b, b)].
    This differs from the previous chapter's map [b] to [(b, negb b)]: our
    syntax has no negation constant. The same product operation underlies
    both constructions. Projecting duplication returns [b] in this model. *)

(** ** 6. 在广集模型中计算

    显式启用 [SetCat_CCC]，并将唯一的基类型标签解释为 [BoolS]。[single_env]
