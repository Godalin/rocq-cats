(** ** 1. Types, contexts and variables

    [Ty B] is generated by base labels [B], unit [⊤], products [A × U] and
    function types [A ⇒ U]. A label is not a term constant: the signature
    currently has no primitive Boolean operations or Boolean literals.

    A context [∅ ▻ A ▻ U] lists two available variables. [𝟘] selects the
    newest one, of type [U]; [↑v 𝟘] selects the older one, of type [A].
    [Tm Γ A] is the type of terms of type [A] in context [Γ]. Typing is
    built into the constructors, so application requires matching types.
    There is no separate well-typedness proof attached after construction.

    We choose one base label [tt]. [Atom] is a syntactic base type; we will
    later interpret it by [BoolS]. Its label does not make the syntax itself
    a language with Boolean constants. *)

(** ** 1. 类型、上下文与变量

    [Ty B] 由基类型标签 [B]、单位 [⊤]、积 [A × U] 和函数类型 [A ⇒ U] 生成。
    标签不是项常量：当前签名没有原始的布尔操作或布尔字面量。

    上下文 [∅ ▻ A ▻ U] 列出两个可用变量。[𝟘] 选择类型为 [U] 的最新变量，
    [↑v 𝟘] 选择类型为 [A] 的旧变量。[Tm Γ A] 是上下文 [Γ] 中类型为 [A]
    的项的类型。类型直接内置于构造器，因此应用要求类型匹配，无需在构造之后
    另附类型正确性证明。

    我们只选择一个基类型标签 [tt]。[Atom] 是语法中的基类型，稍后将它解释为
    [BoolS]。这个标签本身并不会给语法添加布尔常量。 *)

Definition Atom
  : Ty unit
  := ty_base tt.

(** ** 2. Identity and duplication

    [# x] turns a variable into a term. [ƛ t] binds a new input, whereas
    [t · u] applies a function. Inside identity's body, [𝟘] is exactly the
    newly bound input. Identity works in any surrounding context.

    Duplication has one free variable and pairs it with itself. Its context
    has one entry even though the variable occurs twice in its body. These
    are syntax trees, not Rocq functions on semantic values. *)

(** ** 2. 恒等与复制

    [# x] 将变量变为项，[ƛ t] 绑定一个新输入，[t · u] 应用函数。在恒等函数
    的项体中，[𝟘] 正是刚绑定的输入。恒等函数适用于任意外层上下文。

    复制项只有一个自由变量，并将它与自身配对。虽然变量在项体中出现两次，
    上下文仍然只有一个条目。这些是语法树，而不是作用于语义值的 Rocq 函数。 *)

Definition IdentityTerm {B : Type} {Γ : Ctx B} (A : Ty B)
  : Tm Γ (A ⇒ A)
  := ƛ (# 𝟘).

(** Duplicate the single available input. *)

(** 复制唯一可用的输入。 *)

Definition DuplicateTerm {B : Type} (A : Ty B)
  : Tm (∅ ▻ A) (A × A)
  := ⟨# 𝟘, # 𝟘⟩.

(** ** 3. Substitution assigns terms to variables

    A renaming assigns variables to variables; [wkRen] includes old variables
    in an extended context. A simultaneous substitution [Sub Δ Γ] instead
    assigns a term in [Δ] to every variable of [Γ]. Thus [t[σ]] changes the
    context of [t] from [Γ] to [Δ]. Under a lambda, [σ^↑Sub] preserves the
    newly bound variable and weakens the old assignments, avoiding capture.

    [sub_empty ▻Sub t] extends an assignment with a term for its newest
    variable. Here both target variables receive the same source variable.
    The arrow goes from the source context with one input to the target
    context with two components; the substitution assigns both components.
    Substituting into either target variable recovers that input. *)

(** ** 3. 替换为变量赋予项

    重命名为变量赋予变量；[wkRen] 将旧变量嵌入扩张上下文。同时替换
    [Sub Δ Γ] 则为 [Γ] 中的每个变量赋予 [Δ] 中的项。因此 [t[σ]] 将 [t]
    的上下文从 [Γ] 改为 [Δ]。进入 λ 绑定后，[σ^↑Sub] 保留新绑定的变量，
    并弱化旧赋值，从而避免变量捕获。

    [sub_empty ▻Sub t] 用一个项扩张赋值，为最新变量提供内容。这里把两个目标
    变量都赋为同一个源变量。箭头从只有一个输入的源上下文出发，到含两个分量
    的目标上下文；替换同时指定这两个分量。替换任一目标变量都恢复该输入。 *)

Definition DuplicateSub {B : Type} (A : Ty B)
  : Sub (∅ ▻ A) (∅ ▻ A ▻ A)
  := (sub_empty ▻Sub # 𝟘) ▻Sub # 𝟘.

(** Substituting into the older target variable selects its assignment. *)

(** 对较旧的目标变量进行替换，得到为它指定的项。 *)

Example duplicate_sub_older {B : Type} (A : Ty B)
  : (# (↑v 𝟘))[DuplicateSub A] ≈βη # 𝟘.
Proof. reflexivity. Qed.

(** ** 4. Beta and eta are the specified equality of terms

    [t ≈βη u] is a Type-valued equational derivation, generated by
    equivalence, constructor congruence and unit/product/function equations.
    It is the specified equality in the term setoid [TmS Γ A]. We compare
    terms by this equality, without comparing their derivation witnesses.

    Function beta substitutes the argument into the body; identity therefore
    returns its argument. Product beta recovers a paired component, and
    product eta reconstructs a pair from both projections. Function eta
    reconstructs a function by applying it to a fresh input; [wkRen] keeps
    its old variables in scope. These equations will become the
    universal-property laws of a CCC. *)

(** ** 4. β 与 η 是项的指定相等

    [t ≈βη u] 是 Type 值等式推导，由等价关系、构造器同余以及单位、积、函数
    的方程生成。它就是项广集 [TmS Γ A] 的指定相等。我们以这种相等比较项，
    不比较它们的推导见证。

    函数 β 将实参替换进项体，因此恒等函数返回实参。积 β 恢复配对的分量，
    积 η 从两个投影重建原来的配对。函数 η 将函数应用于一个新输入，再由抽象
    重建原函数；[wkRen] 保留它的旧变量。这些方程随后成为 CCC 的泛性质定律。 *)

Example identity_β {B : Type} {Γ : Ctx B} {A : Ty B} (t : Tm Γ A)
  : IdentityTerm A · t ≈βη t.
Proof. exact (tm_eq_function_β (# 𝟘) t). Qed.

(** The first projection of duplication is the input variable. *)

(** 复制项的第一投影就是输入变量。 *)

Example duplicate_β {B : Type} (A : Ty B)
  : π₁ (DuplicateTerm A) ≈βη # 𝟘.
Proof. apply tm_eq_product_β1. Qed.

(** Both projections reconstruct any product term. *)

(** 两个投影重建任意积类型项。 *)

Example pair_η {B : Type} {Γ : Ctx B} {A U : Ty B}
    (t : Tm Γ (A × U))
  : ⟨π₁ t, π₂ t⟩ ≈βη t.
Proof. apply tm_eq_product_η. Qed.

(** Abstracting application to a fresh variable recovers the function. *)

(** 抽象对新变量的应用，恢复原函数。 *)

Example function_η {B : Type} {Γ : Ctx B} {A U : Ty B}
    (t : Tm Γ (A ⇒ U))
  : ƛ (t⟨wkRen⟩ · # 𝟘) ≈βη t.
Proof. apply tm_eq_function_η. Qed.

(** ** 5. A CCC interprets syntax as arrows

    A cartesian closed category (CCC) has a chosen terminal object, binary
    products and exponentials. Currying turns an arrow with an extra input
    into an arrow to a function object; evaluation applies that function.
    Their beta/eta laws interpret abstraction and application.

    Choose a CCC [C] and assign an object [I b] to each base label. [TyI]
    interprets unit by the terminal object, products by products and [A ⇒ U]
    by the exponential from [TyI I A] to [TyI I U]. [CtxI] interprets the
    empty context by the terminal object and extension by product.
    [⟦t⟧Tm[I]] is an arrow from context to type. Pairing and projections
    use the chosen product; abstraction and application use the exponential.

    Soundness [tm_interp_sound] sends beta/eta derivations to the specified
    hom equality. Substitution becomes precomposition by [tm_interp_subst].
    Both results apply to any CCC. *)

(** ** 5. CCC 将语法解释为箭头

    笛卡尔闭范畴（CCC）带有选定的终对象、二元积与指数对象。Currying 将一条
    接收上下文与一个额外输入的箭头，变成从该上下文到函数对象的箭头；求值则
    将这样的函数应用于输入。它们的 βη 定律解释了 CCC 为何能够解释抽象与应用。

    选定 CCC [C]，并为每个基类型标签赋予对象 [I b]。[TyI] 将单位解释为终对象、
    积解释为积，将 [A ⇒ U] 解释为以 [TyI I A] 为定义域、[TyI I U] 为值域的
    指数对象。[CtxI] 将空上下文解释为终对象，将上下文扩张解释为积。
    [⟦t⟧Tm[I]] 是从上下文对象到类型对象的箭头。抽象使用 curry，应用使用
    求值，配对与投影使用选定的积结构。

    可靠性 [tm_interp_sound] 将 βη 推导送到指定的 Hom 相等。替换成为预合成，
    下例直接使用 [tm_interp_subst] 表达这一点。这些是适用于任意 CCC 的一般
    结论，而非仅对布尔例子成立的事实。 *)

Section CategoricalSemantics.

Context {B : Type} {C : Cat} `{HC : !CCC C} (I : B → @Ob C).

(** Interpretation turns substitution into composition. *)

(** 解释将替换变为复合。 *)

Example substitution_as_composition {Γ Δ : Ctx B} {A : Ty B}
    (t : Tm Γ A) (σ : Sub Δ Γ)
  : ⟦t[σ]⟧Tm[I] ≈ ⟦t⟧Tm[I] ∘ sub_interp I σ.
Proof. apply tm_interp_subst. Qed.

(** A syntactic beta equation is a categorical arrow equation. *)

(** 语法 β 方程成为范畴中的箭头方程。 *)

Example interpreted_identity_β {Γ : Ctx B} {A : Ty B} (t : Tm Γ A)
  : ⟦IdentityTerm A · t⟧Tm[I] ≈ ⟦t⟧Tm[I].
Proof. apply tm_interp_sound. apply identity_β. Qed.

End CategoricalSemantics.

(** ** 6. Compute in the setoid model

    Explicitly enable [SetCat_CCC] and interpret the unique base label by
    [BoolS]. [single_env] assigns the identity arrow to the sole variable,
    so evaluating duplication gives the diagonal map [b] to [(b, b)].
    This differs from the previous chapter's map [b] to [(b, negb b)]: our
    syntax has no negation constant. The same product operation underlies
    both constructions. Projecting duplication returns [b] in this model. *)

(** ** 6. 在广集模型中计算

    显式启用 [SetCat_CCC]，并将唯一的基类型标签解释为 [BoolS]。[single_env]
    为唯一变量赋予恒等箭头，因此求值复制项就得到将 [b] 送到 [(b, b)] 的
    对角映射。这与上一章将 [b] 送到 [(b, negb b)] 的映射不同，因为当前语法
    没有取反常量。两个构造使用同一个积运算。在此模型中，复制后取投影返回 [b]。 *)

Local Existing Instance SetCat_CCC.

(** The sole base type denotes the Boolean setoid. *)

(** 唯一基类型表示布尔广集。 *)

Definition BooleanBase (_ : unit)
  : @Ob SetCat
  := BoolS.

(** Evaluate the duplication syntax on one Boolean input. *)

(** 对一个布尔输入求值复制语法。 *)

Example duplicate_boolean_value (b : bool)
  : tm_eval BooleanBase (DuplicateTerm Atom)
      (single_env BooleanBase Atom) b ≈S (b, b).
Proof. split; reflexivity. Qed.

(** Projection after duplication computes to the original Boolean. *)

(** 复制后取投影，计算得到原来的布尔值。 *)

Example duplicate_boolean_projection (b : bool)
  : tm_eval BooleanBase (π₁ (DuplicateTerm Atom))
      (single_env BooleanBase Atom) b ≈S b.
Proof. reflexivity. Qed.

(** ** 7. Syntax itself forms a CCC

    [CtxCat B] has contexts as objects and simultaneous substitutions as
    arrows. Its hom equality is pointwise beta/eta equality, so the identity
    and composition of substitutions give category laws at that equality.
    [CtxCat_CCC] chooses the empty context as terminal, context concatenation
    as product, and packed function contexts as exponentials.

    A context can also be packed into one nested product type: the empty
    context contributes unit and each extension contributes a product.
    [ctx_pack_iso] proves that a context is isomorphic to the singleton
    context containing its packed type. Packing and unpacking assignments
    are inverse by product and unit beta/eta equations.

    [TyCat B] presents the same theory with types as objects and
    singleton-context substitutions as arrows. [ContextCategoryEquivalence]
    compares it with [CtxCat B]. [TypeInterpretF] sends this presentation to
    any chosen CCC; [TypeInterpretF_IsCCCF] proves structure preservation.
    The Boolean assignment therefore extends to the following functor. *)

(** ** 7. 语法自身构成 CCC

    [CtxCat B] 以上下文为对象、同时替换为箭头。其 Hom 相等是逐点 βη 相等，
    因而替换的恒等与复合在这种相等下给出范畴律。[CtxCat_CCC] 选取空上下文
    作为终对象、上下文连接作为积、打包后的函数上下文作为指数对象。

    上下文还可以打包为一个嵌套积类型：空上下文贡献单位，每次扩张贡献一个积。
    [ctx_pack_iso] 证明上下文同构于只含其打包类型的单变量上下文。由单位与积
    的 βη 方程，赋值的打包与拆包互逆。

    [TyCat B] 用类型作为对象、单变量上下文替换作为箭头，呈现同一个理论。
    [ContextCategoryEquivalence] 将它与 [CtxCat B] 比较。[TypeInterpretF]
    将此呈现送到任意选定 CCC，[TypeInterpretF_IsCCCF] 证明它保持结构。因此，
    布尔赋值扩张为下面的函子。 *)

Definition BooleanInterpretation
  : Functor (TyCat unit) SetCat
  := TypeInterpretF BooleanBase.

(** ** 8. Completeness and the free universal property

    Soundness holds in every CCC model. Conversely, at a common universe
    bound containing the syntactic model, equality in all CCC models implies
    beta/eta equality. [tm_soundness_iff_completeness] proves this using
    interpretation back into the syntactic CCC and quotation. [≈CCC] denotes
    validity in all models at those bounds. The next example reuses exactly
    this theorem; it does not claim that equality in the Boolean model alone
    reflects every syntactic equation.

    The free property makes the semantic construction canonical. Given a
    CCC-preserving functor [F] and specified base-type isomorphisms from an
    assignment [I] to [F]'s base images, [type_interpretation_universal]
    supplies a natural isomorphism from [TypeInterpretF I] to [F], unique
    among natural transformations with those base components. Comparison is
    by natural isomorphism, not equality of functor records.

    These are the existing equational and categorical results. Their proofs
    use the syntactic model and universal properties; they do not supply a
    normalization algorithm or a decision procedure for beta/eta equality. *)

(** ** 8. 完备性与自由泛性质

    可靠性在每个 CCC 模型中成立。反过来，在包含语法模型的共同宇宙界内，若
    两项在全部 CCC 模型中相等，则它们 βη 相等。[tm_soundness_iff_completeness]
    通过语法 CCC 中的解释及语法还原来证明这一点。[≈CCC] 表示在这些大小界内
    全部模型中的有效性。下例直接复用此定理，并不声称仅在布尔模型中的相等
    就能反映所有语法方程。

    自由性质使语义构造具有规范性。给定保持 CCC 结构的函子 [F]，以及从基类型
    赋值 [I] 到 [F] 的基类型像的指定同构，[type_interpretation_universal]
    给出从 [TypeInterpretF I] 到 [F] 的自然同构，并证明它在具有这些基类型
    分量的自然变换中唯一。函子按自然同构比较，不要求函子记录相等。

    这些是库中已有的等式与范畴论结论，其证明使用语法模型及泛性质；它们并未
    给出正规化算法或 βη 相等的判定过程。 *)

Example equations_in_all_models {B : Type} {Γ : Ctx B} {A : Ty B}
    (t u : Tm Γ A)
  : t ≈βη u ↔ t ≈CCC u.
Proof. apply tm_soundness_iff_completeness. Defined.

(** ** 9. Inhabitation in every model

    Inhabitation asks for a term [Tm Γ A], rather than an equation between
    two given terms. [TmModelInhabited Γ A] supplies a morphism from [CtxI I Γ]
    to [TyI I A] for every chosen CCC and base interpretation at the same
    common universe bound as [TmModelEq]. This is witness-carrying data in
    [Type]: it does not merely assert nonemptiness in one model.

    [tm_inhabitation_soundness] interprets a term in each model. Conversely,
    [tm_inhabitation_completeness] specializes the family to [TyCat B], uses
    the canonical context and type isomorphisms, and extracts a term from
    the resulting substitution. [tm_inhabitation_soundness_iff_completeness]
    bundles these two maps without asserting equality of their witnesses.

    Under Curry--Howard--Lambek this is provability completeness for truth,
    conjunction and implication. It does not require normalization or a
    decision procedure, nor reconstruct a typing derivation for a given
    untyped term: the syntax is already intrinsically typed. *)

(** ** 9. 所有模型中的可居留性

    可居留性要求一个项 [Tm Γ A]，而非两个给定项之间的等式。
    [TmModelInhabited Γ A] 在与 [TmModelEq] 相同的共同宇宙界内，为每个
    选定 CCC 及基类型解释给出从 [CtxI I Γ] 到 [TyI I A] 的态射。
    这是 [Type] 中携带见证的数据，并非仅断言某个模型中的非空性。

    [tm_inhabitation_soundness] 在每个模型中解释一个项。反向的
    [tm_inhabitation_completeness] 将见证族实例化为 [TyCat B]，使用规范
    上下文与类型同构，再从所得替换中提取项。
    [tm_inhabitation_soundness_iff_completeness] 打包这两个映射，
    不断言见证相等。

    在 Curry--Howard--Lambek 对应下，这是真、合取与蕴含片段的可证性
    完备性。它无须正规化或判定过程，也不为给定无类型项恢复类型推导；
    这里的语法本来就是内在带类型的。 *)
