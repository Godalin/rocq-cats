(** * Simplicial Sets with Specified Equality

    Simplicial sets are setoid-valued presheaves on the simplex category.
    Their maps are natural transformations, compared by pointwise specified
    equality. No quotient or native equality of functions is required.
    Write [X[θ]Δ] for restriction along a simplex operator. *)

(** * 带指定相等的单纯集合

    单纯集合是单纯范畴上的广集值预层；映射是自然变换，按逐点指定相等比较。
    此处不要求商集或函数的原生相等；沿单纯算子的限制记为 [X[θ]Δ]。 *)

(** ** From One Simplex to a Simplicial Set

    A simplex is one piece of data of a given dimension. A simplicial set X
    supplies a whole family: [X 0] contains vertices, [X 1] edges, [X 2]
    triangles, and so on. Each degree is a setoid, so membership includes a
    specified way of comparing data. The word ``set'' does not require native
    Rocq equality here.

    The picture shows the first three shapes. A triangle of X is a chosen
    element of [X 2], with three edges and their endpoints. Different
    triangles may have the same edges; conversely, three edges with matching
    endpoints need not bound a triangle of X. The definition supplies ways
    to read faces, not a rule that every possible boundary has a filling. *)

(** ** 从一个单形到单纯集合

    单形是某个维度的一份数据。单纯集合 X 提供一整族数据：[X 0] 装顶点，
    [X 1] 装边，[X 2] 装三角形，依此类推。每一维都是广集，因此数据还带有
    指定的比较方式。这里“集合”一词并不要求使用 Rocq 的原生相等。

    下图画出最初的三个形状。X 的一个三角形是 [X 2] 中选定的元素，有三条边
    及其端点。不同三角形可能有相同的边；反过来，三条端点相接的边也不一定
    围成 X 的一个三角形。定义提供的是读出面的操作，并不要求每个可能的边界
    都有填充。 *)

(** @lang both
%\begin{center}
\begin{tabular}{ccc}
\begin{tikzcd}[column sep=small,row sep=small]
\bullet
\end{tikzcd}
&
\begin{tikzcd}[column sep=small,row sep=small]
0 \arrow[r] & 1
\end{tikzcd}
&
\begin{tikzcd}[column sep=small,row sep=small]
& 1 \arrow[ddr] & \\
& t & \\
0 \arrow[uur] \arrow[rr] && 2
\end{tikzcd}
\\
$X_0$ & $X_1$ & $X_2$
\end{tabular}
\end{center}%
*)

(** A family of setoids alone is not enough: the same vertex must be obtained
    when faces are taken in different orders. For every monotone shape map
    [θ] from dimension m to n, restriction [X[θ]Δ] takes an n-simplex to an
    m-simplex. This reverses direction. Identity and composite restrictions
    obey %\coqref{Cats.Instance.Set.Simplicial.Core.simplex restrict id}
    {%[simplex_restrict_id]%}% and %\coqref{Cats.Instance.Set.Simplicial.Core.simplex restrict comp}
    {%[simplex_restrict_comp]%}%; these are exactly
    the functor laws hidden in the word ``presheaf''.

    Faces lower degree, while degeneracies raise degree by repeating
    positions; the next chapter makes both explicit. Even the simplicial
    point has data in every degree, all generated by degeneracy from its
    vertex. Thus a finite picture does not mean that high degrees are empty.
    The pictures are geometric guides to this combinatorial data, not an
    additional topological realization.

    A map [α : X ⇒ Y] acts in each degree and commutes with every restriction,
    as %\coqref{Cats.Instance.Set.Simplicial.Core.simplex restrict natural}
    {%[simplex_restrict_natural]%}% states. It therefore sends the faces of a
    triangle to the faces of its image triangle. After faces and degeneracies,
    %\coqref{Cats.Instance.Set.Simplicial.Standard.StandardSimplex}
    {%[StandardSimplex]%}% gives the first
    complete example of such a family. *)

(** 只有一族广集还不够：按不同次序取面，读到同一个顶点时应得到相同结果。
    对每个从 m 维到 n 维的保序形状映射 [θ]，限制 [X[θ]Δ] 把 n-单形送到
    m-单形，方向反转。恒等与复合限制满足 %\coqref{Cats.Instance.Set.Simplicial.Core.simplex restrict id}
    {%[simplex_restrict_id]%}% 和
    %\coqref{Cats.Instance.Set.Simplicial.Core.simplex restrict comp}
    {%[simplex_restrict_comp]%}%；“预层”一词中包含的函子律正是这些要求。

    面降低维数，退化则通过重复位置提高维数，下一章会明确给出两种操作。
    即使单纯点在每一维也都有数据，它们都由唯一顶点反复退化产生。因此，图画
    有限并不表示高维为空。图形帮助理解这些组合数据，此处没有另外构造拓扑
    空间的几何实现。

    映射 [α : X ⇒ Y] 逐维作用，并与每个限制交换，见
    %\coqref{Cats.Instance.Set.Simplicial.Core.simplex restrict natural}
    {%[simplex_restrict_natural]%}%。因此，一个三角形的面会被送到像三角形的面。
    读过面与退化之后，
    %\coqref{Cats.Instance.Set.Simplicial.Standard.StandardSimplex}
    {%[StandardSimplex]%}%
    将给出这种数据族的第一个完整例子。 *)

Definition SimplicialCat@{u p +}
  : Cat
  := Fct (Δ^op) SetCat@{u p _ _ _ _ _}.

Notation sSet := SimplicialCat.

(** Restriction along a simplex operator reverses its direction. Its source
    and target are the original value setoids, with independent sizes. *)

(** 沿单纯算子的限制反转其方向；源和目标沿用原值广集，保持大小的独立性。 *)

Definition simplex_restrict@{u p +}
    {X : Functor (Δ^op) SetCat@{u p _ _ _ _ _}} {m n : nat}
    (θ : (@Hom Δ) m n)
  : X n →r X m
  := fmap X θ.

Notation "X '[' θ ']Δ'" := (simplex_restrict (X := X) θ)
  (at level 8, left associativity, format "X [ θ ]Δ") : hom_scope.

(** Restriction along the identity is the identity map. *)

(** 沿恒等的限制是恒等映射。 *)

Lemma simplex_restrict_id@{u p +}
    {X : Functor (Δ^op) SetCat@{u p _ _ _ _ _}} (n : nat)
  : X[(id : (@Hom Δ) n n)]Δ ≈f id_resp.
Proof. exact (functor_id _ _ X). Qed.

(** Read this triangle from [X n]. The shape maps go from l to m
    to n, but their restrictions go from [X n] to [X m] to [X l]. Reading
    both restrictions in succession agrees with reading their composite.
    This is the contravariance in %\coqref{Cats.Instance.Set.Simplicial.Core.simplex restrict comp}
    {%[simplex_restrict_comp]%}%. For example,
    reading an edge of a triangle and then one of that edge's endpoints
    agrees with directly reading that vertex of the triangle. *)

(** 从 [X n] 出发读下图。形状映射从 l 到 m 再到 n，限制却从 [X n] 到
    [X m] 再到 [X l]。依次读出两次限制，等于沿复合一次读出。这就是
    %\coqref{Cats.Instance.Set.Simplicial.Core.simplex restrict comp}
    {%[simplex_restrict_comp]%}% 的反变性。例如，先取三角形的一条边，再取这条边
    的一个端点，等于直接取三角形的那个顶点。 *)

(** @lang both
%\begin{center}
\begin{tikzcd}[column sep=huge,row sep=large]
X_n \arrow[r,"{X[\theta]}"] \arrow[dr,"{X[\theta\circ\varphi]}"'] &
X_m \arrow[d,"{X[\varphi]}"] \\
& X_l
\end{tikzcd}
\end{center}%
*)

(** Restriction reverses composition. *)

(** 限制反转复合次序。 *)

Lemma simplex_restrict_comp@{u p +}
    {X : Functor (Δ^op) SetCat@{u p _ _ _ _ _}} {l m n : nat}
    (θ : (@Hom Δ) m n) (φ : (@Hom Δ) l m)
  : X[θ ∘ φ]Δ ≈f (X[φ]Δ ∘r X[θ]Δ).
Proof. exact (functor_comp _ _ X φ θ). Qed.

(** Equivalent simplex operators induce equal restriction maps. *)

(** 等价的单纯算子诱导相等的限制映射。 *)

Global Instance simplex_restrict_proper@{u p +}
    {X : Functor (Δ^op) SetCat@{u p _ _ _ _ _}} {m n : nat}
  : Proper (@HomEq Δ m n ==> FunEq) (@simplex_restrict X m n).
Proof. exact (@functor_fmap_proper _ _ X n m). Qed.

(** ** The Compatibility Square for a Simplicial Map

    For a shape operator [θ] from m to n, the vertical arrows below read
    the corresponding restriction. Starting with any n-simplex in X, the
    two routes to [Y m] agree in specified equality. This is the naturality
    equation %\coqref{Cats.Instance.Set.Simplicial.Core.simplex restrict natural}
    {%[simplex_restrict_natural]%}%. Choosing a coface says that mapping
    a simplex and then taking a face agrees with taking the face first. *)

(** ** 单纯映射的相容方块

    对从 m 到 n 的形状算子 [θ]，下图的竖箭头读出相应限制。从 X 的任意
    n-单形出发，两条通往 [Y m] 的路径在指定相等下相等。这就是自然性方程
    %\coqref{Cats.Instance.Set.Simplicial.Core.simplex restrict natural}
    {%[simplex_restrict_natural]%}%。特别地，选取余面时，先映射再取面与先取面
    再映射得到相同结果。 *)

(** @lang both
%\begin{center}
\begin{tikzcd}[column sep=large,row sep=large]
X_n \arrow[r,"{\alpha_n}"] \arrow[d,"{X[\theta]}"'] &
Y_n \arrow[d,"{Y[\theta]}"] \\
X_m \arrow[r,"{\alpha_m}"'] & Y_m
\end{tikzcd}
\end{center}%
*)

(** A map of simplicial sets commutes with every restriction. *)

(** 单纯集合映射与每个限制交换。 *)

Lemma simplex_restrict_natural@{u p +}
    {X Y : Functor (Δ^op) SetCat@{u p _ _ _ _ _}}
    (α : X ⇒ Y) {m n : nat} (θ : (@Hom Δ) m n)
  : (α m ∘r X[θ]Δ) ≈f (Y[θ]Δ ∘r α n).
Proof. exact (nt_naturality α θ). Qed.
