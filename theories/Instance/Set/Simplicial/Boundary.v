From Cats Require Export
  Instance.Set.Simplicial.Standard
  Instance.Set.Sieve.
From Cats Require Import
  Cat.Morphism.

Local Open Scope nat_scope.

(** * Boundaries and Horns Generated by Faces

    These are actual simplicial subobjects of standard simplices. A simplex
    retains a chosen face factorization, but equality compares only its
    underlying simplex operator. The zero-dimensional boundary is empty. *)

(** * 由面生成的边界与 horn

    这些是标准单形的实际单纯子对象。单形保留选定的面分解，但相等只比较底层
    单纯算子。零维边界为空。 *)

(** All codimension-one faces generate the boundary sieve. *)

(** 全部余维一的面生成边界筛。 *)

Definition BoundarySieve (n : nat)
  : Sieve Δ n
  := match n with
  | 0 => EmptySieve Δ 0
  | S m => @GeneratedSieve Δ (S m) (Ordinal (S m))
      (λ _, m) (λ i, δ[m; i])
  end.

(** Exclude the specified face from the generating family. At dimension
    zero the sieve is empty; filling conditions below use positive dimensions. *)

(** 从生成族中排除指定的面。零维时筛为空；后续填充条件只使用正维度。 *)

Definition HornSieve (n : nat) (i : Ordinal n)
  : Sieve Δ n
  := match n as d return Ordinal d → Sieve Δ d with
  | 0 => λ _, EmptySieve Δ 0
  | S m => λ k, @GeneratedSieve Δ (S m)
      (∃ j : Ordinal (S m), ¬ j = k) (λ _, m) (λ j, δ[m; j.1])
  end i.

(** Realize the boundary sieve as a simplicial setoid. *)

(** 将边界筛实现为单纯广集。 *)

Definition Boundary@{u p +} (n : nat)
  : Functor (Δ^op) SetCat@{u p _ _ _ _ _}
  := SievePsh (BoundarySieve n).

Notation "'∂Δ[' n ']'" := (Boundary n) : ob_scope.

(** Realize the horn sieve using the same subpresheaf construction. *)

(** 使用同一子预层构造实现 horn 筛。 *)

Definition Horn@{u p +} (n : nat) (i : Ordinal n)
  : Functor (Δ^op) SetCat@{u p _ _ _ _ _}
  := SievePsh (HornSieve n i).

Notation "'Λ[' n ';' i ']'" := (Horn n i) : ob_scope.

(** Include the boundary in its standard simplex. *)

(** 将边界包含到其标准单形中。 *)

Definition BoundaryInclusionN@{u p +} (n : nat)
  : (∂Δ[n] : Functor (Δ^op) SetCat@{u p _ _ _ _ _}) ⇒ Δ[n]
  := ιSv[BoundarySieve n].

Notation "'ι∂[' n ']'" := (BoundaryInclusionN n) : hom_scope.

(** Include a horn in its standard simplex. *)

(** 将 horn 包含到其标准单形中。 *)

Definition HornInclusionN@{u p +} (n : nat) (i : Ordinal n)
  : (Λ[n; i] : Functor (Δ^op) SetCat@{u p _ _ _ _ _}) ⇒ Δ[n]
  := ιSv[HornSieve n i].

Notation "'ιΛ[' n ';' i ']'" := (HornInclusionN n i) : hom_scope.

(** Boundary inclusion is a monomorphism in the simplicial category. *)

(** 边界包含是单纯范畴中的单态射。 *)

Program Definition BoundaryMono@{u p +} (n : nat)
  : @Mono (Fct (Δ^op) SetCat@{u p _ _ _ _ _}) ∂Δ[n] Δ[n]
  :=
  {|mor := ι∂[n]
  |}.
Next Obligation. exact (@sieve_inclusion_mono Δ n (BoundarySieve n)). Defined.

(** Horn inclusion is monic for the same reason. *)

(** 同理，horn 的包含也是单态射。 *)

Program Definition HornMono@{u p +} (n : nat) (i : Ordinal n)
  : @Mono (Fct (Δ^op) SetCat@{u p _ _ _ _ _}) Λ[n; i] Δ[n]
  :=
  {|mor := ιΛ[n; i]
  |}.
Next Obligation. exact (@sieve_inclusion_mono Δ n (HornSieve n i)). Defined.

(** Every horn member is a boundary member, by forgetting the excluded-face
    condition while retaining the same chosen factorization. *)

(** 忘却排除面的条件并保留同一选定分解，得到 horn 隶属到边界隶属的转换。 *)

Definition horn_sieve_boundary (n : nat) (i : Ordinal n)
    (m : nat) (f : (@Hom Δ) m n)
  : f ∈Sv HornSieve n i → f ∈Sv BoundarySieve n.
Proof.
  destruct n as [| n]; cbn; intros H.
  - exact H.
  - destruct H as [[j Hj] [g E]]. exists j, g. exact E.
Defined.

(** The generic top-dimensional simplex is not a boundary member. A face
    factorization would send its omitted vertex into that face's image. *)

(** 泛顶维单形不属于边界；若有面分解，其被省略的顶点便落入该面的像，产生矛盾。 *)

Definition boundary_generic_not_member (n : nat)
  : ¬ (@Cat.Core.id Δ n) ∈Sv BoundarySieve n.
Proof.
  destruct n as [| n]; intros [i [h H]]; [destruct i |].
  pose proof (fst (simplex_eq_iff _ _) H i) as E.
  exact (@fin_skip_avoids (S n) i (h i) (symmetry E)).
Defined.

(** No horn contains the generic top-dimensional simplex either. *)

(** horn 同样不包含泛顶维单形。 *)

Definition horn_generic_not_member (n : nat) (i : Ordinal n)
  : ¬ (@Cat.Core.id Δ n) ∈Sv HornSieve n i
  := λ H, boundary_generic_not_member n
      (horn_sieve_boundary n i n (@Cat.Core.id Δ n) H).

(** Factor horn inclusion through the boundary. *)

(** horn 包含经过边界分解。 *)

Definition HornBoundaryN@{u p +} (n : nat) (i : Ordinal n)
  : (Λ[n; i] : Functor (Δ^op) SetCat@{u p _ _ _ _ _}) ⇒ ∂Δ[n]
  := @SieveMapN Δ n (HornSieve n i) (BoundarySieve n)
      (horn_sieve_boundary n i).

(** The two inclusions commute with the horn-to-boundary map. *)

(** 两个包含映射与 horn 到边界的映射交换。 *)

Lemma horn_boundary_comm@{u p +} (n : nat) (i : Ordinal n)
  : (ι∂[n] ∘Nv (HornBoundaryN n i :
      (Λ[n; i] : Functor (Δ^op) SetCat@{u p _ _ _ _ _}) ⇒ _)) ≈N ιΛ[n; i].
Proof.
  exact (@sieve_map_inclusion Δ n (HornSieve n i) (BoundarySieve n)
    (horn_sieve_boundary n i)).
Defined.

(** Every coface has a canonical boundary membership witness. *)

(** 每个余面均具有典范的边界隶属见证。 *)

Definition boundary_face_member {n : nat} (i : Ordinal (S n))
  : δ[n; i] ∈Sv BoundarySieve (S n)
  := @generated_sieve_member Δ (S n) (Ordinal (S n)) (λ _, n)
      (λ j, δ[n; j]) i.

(** A retained face has a canonical horn membership witness. *)

(** 保留的面具有典范的 horn 隶属见证。 *)

Definition horn_face_member {n : nat} (i j : Ordinal (S n))
    (H : ¬ j = i)
  : δ[n; j] ∈Sv HornSieve (S n) i
  := @generated_sieve_member Δ (S n)
      (∃ j : Ordinal (S n), ¬ j = i) (λ _, n) (λ k, δ[n; k.1]) (j; H).

(** Each face map factors through the boundary by general sieve restriction. *)

(** 通过一般筛的限制，每个面映射经过边界分解。 *)

Definition BoundaryFaceN@{u p +} {n : nat} (i : Ordinal (S n))
  : (Δ[n] : Functor (Δ^op) SetCat@{u p _ _ _ _ _}) ⇒ ∂Δ[S n]
  := @SieveFactorN Δ (S n) n (BoundarySieve (S n))
      δ[n; i] (boundary_face_member i).

(** Every retained face factors through the horn in the same way. *)

(** 每个保留的面以同样方式经过 horn 分解。 *)

Definition HornFaceN@{u p +} {n : nat} (i j : Ordinal (S n))
    (H : ¬ j = i)
  : (Δ[n] : Functor (Δ^op) SetCat@{u p _ _ _ _ _}) ⇒ Λ[S n; i]
  := @SieveFactorN Δ (S n) n (HornSieve (S n) i)
      δ[n; j] (horn_face_member i j H).

(** Including a boundary face recovers its standard coface map. *)

(** 边界面后接包含映射，恢复标准余面映射。 *)

Lemma boundary_face_comm@{u p +} {n : nat} (i : Ordinal (S n))
  : (ι∂[S n] ∘Nv (BoundaryFaceN i :
      (Δ[n] : Functor (Δ^op) SetCat@{u p _ _ _ _ _}) ⇒ _))
      ≈N fmap StandardSimplexF δ[n; i].
Proof.
  exact (@sieve_factor_comm Δ (S n) n (BoundarySieve (S n))
    δ[n; i] (boundary_face_member i)).
Defined.

(** Including a horn face also recovers its standard coface map. *)

(** horn 面后接包含映射，同样恢复标准余面映射。 *)

Lemma horn_face_comm@{u p +} {n : nat} (i j : Ordinal (S n))
    (H : ¬ j = i)
  : (ιΛ[S n; i] ∘Nv (HornFaceN i j H :
      (Δ[n] : Functor (Δ^op) SetCat@{u p _ _ _ _ _}) ⇒ _))
      ≈N fmap StandardSimplexF δ[n; j].
Proof.
  exact (@sieve_factor_comm Δ (S n) n (HornSieve (S n) i)
    δ[n; j] (horn_face_member i j H)).
Defined.
