From Cats Require Import
  Cat.Core
  Cat.Functor
  Cat.Natural
  Cat.Terminal
  Cat.Product
  Cat.Equalizer.
From Cats Require Export
  Graph.Finite
  Cat.Product.Finite
  Cat.Product.Sigma
  Cat.Limit.Graph.

(** * Limits of Diagrams Generated by Finite Graphs *)

(** * 有限图生成的图式的极限 *)

Section FiniteGraphLimits.
Context {C : Cat} `{HT : !HasTerminal C} `{HP : !HasProduct C}.

(** The total edge index is a dependent sum over both endpoints and the finite
    labels between them. Nested finite products supply its product. *)

(** 总边索引是依次遍历两个端点及其间有限标签的依赖和，嵌套有限积给出对应的积。 *)

Definition FiniteGraphEdgeProducts {n : nat} (k : Fin n → Fin n → nat)
  : HasLimitsOfShape C (DiscreteCat (GraphEdges (FiniteGraph k)))
  := @SigmaProductLimits C (Fin n) (λ x, ∃ y : Fin n, Fin (k x y))
    (FiniteProductLimits n)
    (λ x, @SigmaProductLimits C (Fin n) (λ y, Fin (k x y))
      (FiniteProductLimits n) (λ y, FiniteProductLimits (k x y))).

(** Terminal objects, binary products and equalizers give limits for a finite
    graph's free shape. *)

(** 终对象、二元积和等化子给出有限图自由形状的极限。 *)

Definition FiniteGraphLimits `{HE : !HasEqualizer C} {n : nat}
    (k : Fin n → Fin n → nat)
  : HasLimitsOfShape C (FreeCat (FiniteGraph k))
  := @GraphProductsEqualizerLimits (FiniteGraph k) C
    (FiniteProductLimits n) (FiniteGraphEdgeProducts k) HE.

(** Select the limit of one diagram generated by a finite graph. *)

(** 选择一个有限图生成的图式的极限。 *)

Definition FiniteGraphLimit `{HE : !HasEqualizer C} {n : nat}
    (k : Fin n → Fin n → nat) (D : Functor (FreeCat (FiniteGraph k)) C)
  : HasLimit C D
  := @hasLimit C _ (FiniteGraphLimits k) D.

End FiniteGraphLimits.
