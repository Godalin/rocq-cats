From Cats Require Export
  Cat.Shape.Discrete
  Cat.Shape.Order
  Cat.Shape.Ordinal.
From Cats Require Export Graph.Shape.

(** * Free Cospan and Span Shapes *)

(** * 自由余跨度与跨度形状 *)

(** The free shape of two arrows into a common vertex. *)

(** 两条箭头指向共同顶点的自由形状。 *)

Definition CospanShape
  := FreeCat CospanGraph.
(** The opposite of the free cospan shape. *)

(** 自由余跨度形状的反范畴。 *)

Definition SpanShape
  := CospanShape^op.
(** The free shape generated by two parallel arrows. *)

(** 两条平行箭头生成的自由形状。 *)

Definition ParallelShape
  := FreeCat ParallelGraph.
