From Cats Require Export
  Cat.Free
  Graph.Finite.
From Cats Require Import
  Cat.Core
  Cat.Functor.

(** * Finitely Generated Shapes and Finite Hom Covers

    Objects are represented up to isomorphism, and arrows up to their
    specified equality. All covering witnesses are retained in [Type]. *)

(** * 有限生成形状与有限 Hom 覆盖

    对象按同构取代表，箭头按指定相等取代表；所有覆盖见证均保留在 [Type] 中。 *)

(** A finite generating graph with a full, essentially surjective path
    interpretation. No list of path relations is part of this structure;
    the target category already supplies its arrow equality. *)

(** 有限生成图及其满且本质满的路径解释。不要求列出路径关系，目标范畴已经给出
    箭头相等。 *)

Class HasFiniteGenerators (J : Cat)
  :=
  { generator_count : nat
  ; generator_edges : Fin generator_count → Fin generator_count → nat
  ; generator_functor : Functor (FreeCat (FiniteGraph generator_edges)) J
  ; generator_full : is_full generator_functor
  ; generator_essentially_surjective
      : is_essentially_surjective generator_functor
  }.

Arguments generator_count {_} {_}.
Arguments generator_edges {_} {_} _ _.
Arguments generator_functor {_} {_}.
Arguments generator_full {_} {_} _ _ _.
Arguments generator_essentially_surjective {_} {_} _.

(** A finite graph's free category is generated by that graph, even when
    cycles produce infinitely many paths. *)

(** 有限图的自由范畴由该图生成，即使循环产生无限多条路径也成立。 *)

Program Definition FiniteGraphGenerators {n : nat}
    (k : Fin n → Fin n → nat)
  : HasFiniteGenerators (FreeCat (FiniteGraph k))
  :=
  {|generator_count := n
  ; generator_edges := k
  ; generator_functor := IdF
  |}.
Next Obligation. intros i j f. exists f. reflexivity. Defined.
Next Obligation.
  intros i. exists i, id, id. split; apply comp_id_l.
Defined.

(** A finite object cover up to isomorphism, with finite covers of every
    hom-setoid between its representatives. Repeated representatives are
    allowed; this does not require a skeleton or native object equality. *)

(** 按同构给出有限对象覆盖，并覆盖代表对象之间的各个 Hom 广集。允许重复代表，
    不要求骨架或对象的原生相等。 *)

Class HasFiniteHomCover (J : Cat)
  :=
  { finite_object_count : nat
  ; finite_object : Fin finite_object_count → @Ob J
  ; finite_object_cover (X : @Ob J) : ∃ i, finite_object i ≅ X
  ; hasFiniteHom (i j : Fin finite_object_count)
      :: HasFiniteCover (HomSet (finite_object i) (finite_object j))
  }.

Arguments finite_object_count {_} {_}.
Arguments finite_object {_} {_} _.
Arguments finite_object_cover {_} {_} _.
Arguments hasFiniteHom {_} {_} _ _.

Section FiniteHomGenerators.
Context {J : Cat} `{HJ : !HasFiniteHomCover J}.

(** Use one generating edge for each selected representative of a hom-set. *)

(** 为每个选定的 Hom 代表使用一条生成边。 *)

Definition FiniteHomEdges (i j : Fin finite_object_count)
  : nat
  := @finite_count _ (hasFiniteHom i j).

(** Interpret the finite graph using the object and hom enumerations. *)

(** 用对象代表与 Hom 枚举解释有限图。 *)

Program Definition FiniteHomGraphMap
  : FiniteGraph FiniteHomEdges →G UnderlyingGraph J
  :=
  {|vertex_map := finite_object
  ; edge_map i j := @finite_enum _ (hasFiniteHom i j)
  |}.

(** Extend the finite hom enumeration to paths by the free-category theory. *)

(** 通过自由范畴理论将有限 Hom 枚举延拓到路径。 *)

Definition FiniteHomF
  : Functor (FreeCat (FiniteGraph FiniteHomEdges)) J
  := FreeF FiniteHomGraphMap.

(** Every target arrow has a one-edge preimage, up to specified equality. *)

(** 每条目标箭头均按指定相等具有单条边构成的原像。 *)

Definition finite_hom_full
  : is_full FiniteHomF.
Proof.
  intros i j f.
  destruct (@finite_cover _ (hasFiniteHom i j) f) as [e He].
  exists (@path_edge (FiniteGraph FiniteHomEdges) i j e). exact He.
Defined.

(** The object representatives provide essential surjectivity directly. *)

(** 对象代表直接给出本质满性。 *)

Definition finite_hom_essentially_surjective
  : is_essentially_surjective FiniteHomF
  := finite_object_cover.

(** Finite hom covers supply finite generators, without comparing equality
    witnesses or adding path quotients. Enable the result explicitly. *)

(** 有限 Hom 覆盖给出有限生成元，不比较相等见证，也不构造路径商；结果须显式启用。 *)

Program Definition FiniteHomGenerators
  : HasFiniteGenerators J
  :=
  {|generator_count := finite_object_count
  ; generator_edges := FiniteHomEdges
  ; generator_functor := FiniteHomF
  ; generator_full := finite_hom_full
  ; generator_essentially_surjective := finite_hom_essentially_surjective
  |}.

End FiniteHomGenerators.
