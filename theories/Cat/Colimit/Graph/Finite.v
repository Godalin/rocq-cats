(** * Colimits of Diagrams Generated by Finite Graphs *)

(** * 有限图生成的图式的余极限 *)

(** Nested finite coproducts cover the reversed generators' total index. *)

(** 嵌套有限余积覆盖反向生成边的总索引。 *)

Definition FiniteGraphEdgeCoproducts {C : Cat}
    `{HI : !HasInitial C} `{HC : !HasCoproduct C}
    {n : nat} (k : Fin n → Fin n → nat)
  : HasColimitsOfShape C (DiscreteCat (GraphEdges (FiniteGraph k)))
  := @SigmaCoproductColimits C (Fin n) (λ x, ∃ y : Fin n, Fin (k x y))
      (FiniteCoproductColimits n)
      (λ x, @SigmaCoproductColimits C (Fin n) (λ y, Fin (k x y))
        (FiniteCoproductColimits n) (λ y, FiniteCoproductColimits (k x y))).

(** Initial objects, binary coproducts and coequalizers give colimits for
    a finite graph's free shape, including graphs with cycles. *)

(** 始对象、二元余积及余等化子给出有限图自由形状的余极限，包括含环图。 *)

Definition FiniteGraphColimits {C : Cat}
    `{HI : !HasInitial C} `{HC : !HasCoproduct C}
    `{HE : !HasCoequalizer C} {n : nat} (k : Fin n → Fin n → nat)
  : HasColimitsOfShape C (FreeCat (FiniteGraph k))
  := @GeneratedColimits C (FreeCat (FiniteGraph k)) HI HC HE
      (FiniteGraphGen k).

(** Select one finite-generator free-diagram colimit. *)

(** 选择单个有限生成自由图式的余极限。 *)

Definition FiniteGraphColimit {C : Cat}
    `{HI : !HasInitial C} `{HC : !HasCoproduct C}
    `{HE : !HasCoequalizer C} {n : nat} (k : Fin n → Fin n → nat)
    (D : Fct (FreeCat (FiniteGraph k)) C)
  : HasColimit C D
  := @hasColimit _ C (FiniteGraphColimits k) D.
