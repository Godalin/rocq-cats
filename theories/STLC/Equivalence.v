From Cats Require Export STLC.Substitution.
From Cats.Set Require Import Morphism.

(** * Beta/Eta Equality of Typed Terms

    Equality is the Type-valued equivalence and constructor congruence
    generated by the unit, product and function equations. Substitution
    stability is proved from these generators. Derivations retain their
    intermediate terms, so their universe bounds the raw signature level. *)

(** * 带类型项的 βη 相等

    相等是由单位、积、函数方程生成的 Type 值等价关系与构造器同余。替换稳定性
    由生成规则证明。推导保留中间项，因此其宇宙须容纳原始签名层级。 *)

Local Open Scope stlc_ty_scope.
Local Open Scope stlc_ctx_scope.
Local Open Scope stlc_tm_scope.
Local Open Scope stlc_ren_scope.
Local Open Scope stlc_sub_scope.

(** Finite equational derivations, with no quotient types or comparison of
    derivation witnesses. The witness level may exceed the signature level. *)

(** 有限等式推导，不构造商类型，也不比较推导见证；见证层级可严格高于签名层级。 *)

Inductive TmEq@{b e +} {B : Type@{b}}
  : ∀ {Γ : Ctx B} {A : Ty B}, Tm Γ A → Tm Γ A → Type@{e}
  := | tm_eq_refl {Γ A} (t : Tm Γ A) : TmEq t t
     | tm_eq_sym {Γ A} {t u : Tm Γ A} : TmEq t u → TmEq u t
     | tm_eq_trans {Γ A} {t u v : Tm Γ A}
         : TmEq t u → TmEq u v → TmEq t v
     | tm_eq_pair {Γ A U} {t t' : Tm Γ A} {u u' : Tm Γ U}
         : TmEq t t' → TmEq u u' → TmEq (⟨t, u⟩) (⟨t', u'⟩)
     | tm_eq_fst {Γ A U} {t u : Tm Γ (A × U)}
         : TmEq t u → TmEq (π₁ t) (π₁ u)
     | tm_eq_snd {Γ A U} {t u : Tm Γ (A × U)}
         : TmEq t u → TmEq (π₂ t) (π₂ u)
     | tm_eq_lam {Γ A U} {t u : Tm (Γ ▻ A) U}
         : TmEq t u → TmEq (ƛ t) (ƛ u)
     | tm_eq_app {Γ A U} {t t' : Tm Γ (A ⇒ U)} {u u' : Tm Γ A}
         : TmEq t t' → TmEq u u' → TmEq (t · u) (t' · u')
     | tm_eq_unit_η {Γ} (t : Tm Γ ⊤) : TmEq t ⋆
     | tm_eq_product_β1 {Γ A U} (t : Tm Γ A) (u : Tm Γ U)
         : TmEq (π₁ ⟨t, u⟩) t
     | tm_eq_product_β2 {Γ A U} (t : Tm Γ A) (u : Tm Γ U)
         : TmEq (π₂ ⟨t, u⟩) u
     | tm_eq_product_η {Γ A U} (t : Tm Γ (A × U))
         : TmEq (⟨π₁ t, π₂ t⟩) t
     | tm_eq_function_β {Γ A U} (t : Tm (Γ ▻ A) U) (u : Tm Γ A)
         : TmEq ((ƛ t) · u) t[u/]
     | tm_eq_function_η {Γ A U} (t : Tm Γ (A ⇒ U))
         : TmEq (ƛ (t⟨wkRen⟩ · # var_zero)) t.

Infix "≈βη" := TmEq (at level 50, no associativity) : stlc_tm_scope.

(** The generating reflexivity, symmetry and transitivity give equivalence. *)

(** 生成规则中的自反、对称及传递给出等价关系。 *)

Global Instance TmEq_Equivalence@{b e +} {B : Type@{b}}
    {Γ : Ctx B} {A : Ty B}
  : Equivalence (@TmEq@{b e _} B Γ A).
Proof.
  split.
  - exact tm_eq_refl.
  - intros t u H. exact (tm_eq_sym H).
  - intros t u v H K. exact (tm_eq_trans H K).
Defined.

(** Structural equality of raw terms is included in beta/eta equality. *)

(** 原始项的结构相等包含于 βη 相等。 *)

Definition tm_eq_of_eq@{b e +} {B : Type@{b}}
    {Γ : Ctx B} {A : Ty B} {t u : Tm Γ A}
    (H : t = u)
  : TmEq@{b e _} t u.
Proof. destruct H. apply tm_eq_refl. Defined.

(** Renaming preserves every equational generator, including the function
    equations whose bodies require lifted renamings. *)

(** 重命名保持所有等式生成规则，包括项体需要提升重命名的函数方程。 *)

Definition tm_eq_rename@{b e +} {B : Type@{b}}
    {Γ : Ctx B} {A : Ty B}
    {t u : Tm Γ A} (H : TmEq@{b e _} t u)
  : ∀ Δ (ρ : Ren Δ Γ), TmEq@{b e _} t⟨ρ⟩ u⟨ρ⟩.
Proof.
  induction H; intros Δ ρ; cbn.
  - apply tm_eq_refl.
  - apply tm_eq_sym. apply IHTmEq.
  - eapply tm_eq_trans; [apply IHTmEq1 | apply IHTmEq2].
  - apply tm_eq_pair; [apply IHTmEq1 | apply IHTmEq2].
  - apply tm_eq_fst. apply IHTmEq.
  - apply tm_eq_snd. apply IHTmEq.
  - apply tm_eq_lam. apply IHTmEq.
  - apply tm_eq_app; [apply IHTmEq1 | apply IHTmEq2].
  - apply tm_eq_unit_η.
  - apply tm_eq_product_β1.
  - apply tm_eq_product_β2.
  - apply tm_eq_product_η.
  - rewrite rename_single. apply tm_eq_function_β.
  - rewrite rename_weaken. apply tm_eq_function_η.
Defined.

(** Substitutions are beta/eta equal when all their assigned terms are equal.
    Raw pointwise structural equality remains available as [SubEq]. *)

(** 替换的 βη 相等逐点比较所赋项；原始逐点结构相等仍由 [SubEq] 表示。 *)

Definition SubTmEq@{b e +} {B : Type@{b}}
    {Δ Γ : Ctx B} (σ τ : Sub Δ Γ)
  : Type@{e}
  := ∀ A x, TmEq@{b e _} (σ A x) (τ A x).

Infix "≈SubTm" := SubTmEq (at level 50, no associativity) : stlc_sub_scope.

(** Pointwise beta/eta equality of substitutions is an equivalence. *)

(** 替换的逐点 βη 相等构成等价关系。 *)

Global Instance SubTmEq_Equivalence@{b e +} {B : Type@{b}}
    {Δ Γ : Ctx B}
  : Equivalence (@SubTmEq@{b e _} B Δ Γ).
Proof.
  split.
  - intros σ A x. apply tm_eq_refl.
  - intros σ τ H A x. apply tm_eq_sym. apply H.
  - intros σ τ ν H K A x. eapply tm_eq_trans; [apply H | apply K].
Defined.

(** Raw substitution equality embeds into pointwise beta/eta equality. *)

(** 原始替换相等嵌入逐点 βη 相等。 *)

Definition sub_tm_eq_of_eq@{b e +} {B : Type@{b}}
    {Δ Γ : Ctx B} {σ τ : Sub Δ Γ}
    (H : σ ≈Sub τ)
  : SubTmEq@{b e _} σ τ.
Proof. intros A x. apply tm_eq_of_eq. apply H. Defined.

(** Lifting preserves pointwise beta/eta equality by renaming old assignments. *)

(** 提升通过重命名旧赋值保持逐点 βη 相等。 *)

Global Instance sub_lift_tm_proper@{b e +} {B : Type@{b}}
    {Γ Δ : Ctx B} {A : Ty B}
  : Proper (SubTmEq@{b e _} ==> SubTmEq@{b e _}) (@sub_lift B Γ Δ A).
Proof.
  intros σ τ H U [x | x]; cbn.
  - apply tm_eq_rename. apply H.
  - apply tm_eq_refl.
Defined.

(** Replacing assignments by beta/eta equal terms preserves each raw term. *)

(** 将赋值换为 βη 相等的项时，对任意原始项的替换结果仍相等。 *)

Definition subst_tm_ext@{b e +} {B : Type@{b}}
    {Γ : Ctx B} {A : Ty B} (t : Tm Γ A)
  : ∀ Δ (σ τ : Sub Δ Γ),
      SubTmEq@{b e _} σ τ → TmEq@{b e _} t[σ] t[τ].
Proof.
  induction t; intros Δ σ τ H; cbn.
  - apply H.
  - apply tm_eq_refl.
  - apply tm_eq_pair; [apply IHt1 | apply IHt2]; exact H.
  - apply tm_eq_fst. apply IHt. exact H.
  - apply tm_eq_snd. apply IHt. exact H.
  - apply tm_eq_lam. apply IHt. now apply sub_lift_tm_proper.
  - apply tm_eq_app; [apply IHt1 | apply IHt2]; exact H.
Defined.

(** Simultaneous substitution preserves every beta/eta derivation. Function
    beta uses the raw replacement law; eta uses weakening compatibility. *)

(** 同时替换保持每个 βη 推导；函数 β 使用原始代入交换律，η 使用弱化相容性。 *)

Definition tm_eq_subst@{b e +} {B : Type@{b}}
    {Γ : Ctx B} {A : Ty B}
    {t u : Tm Γ A} (H : TmEq@{b e _} t u)
  : ∀ Δ (σ : Sub Δ Γ), TmEq@{b e _} t[σ] u[σ].
Proof.
  induction H; intros Δ σ; cbn.
  - apply tm_eq_refl.
  - apply tm_eq_sym. apply IHTmEq.
  - eapply tm_eq_trans; [apply IHTmEq1 | apply IHTmEq2].
  - apply tm_eq_pair; [apply IHTmEq1 | apply IHTmEq2].
  - apply tm_eq_fst. apply IHTmEq.
  - apply tm_eq_snd. apply IHTmEq.
  - apply tm_eq_lam. apply IHTmEq.
  - apply tm_eq_app; [apply IHTmEq1 | apply IHTmEq2].
  - apply tm_eq_unit_η.
  - apply tm_eq_product_β1.
  - apply tm_eq_product_β2.
  - apply tm_eq_product_η.
  - rewrite subst_single. apply tm_eq_function_β.
  - rewrite subst_weaken. apply tm_eq_function_η.
Defined.

(** Variable terms respect structural variable equality. *)

(** 变量项保持变量的结构相等。 *)

Global Instance tm_var_proper@{b e +} {B : Type@{b}}
    {Γ : Ctx B} {A : Ty B}
  : Proper (eq ==> TmEq@{b e _}) (@tm_var B Γ A).
Proof. intros x y H. apply tm_eq_of_eq. now rewrite H. Defined.

(** Pairing respects beta/eta equality in both components. *)

(** 配对保持两个分量的 βη 相等。 *)

Global Instance tm_pair_proper@{b e +} {B : Type@{b}}
    {Γ : Ctx B} {A U : Ty B}
  : Proper (TmEq@{b e _} ==> TmEq@{b e _} ==> TmEq@{b e _})
      (@tm_pair B Γ A U).
Proof. intros t t' H u u' K. exact (tm_eq_pair H K). Defined.

(** First projection respects beta/eta equality. *)

(** 第一投影保持 βη 相等。 *)

Global Instance tm_fst_proper@{b e +} {B : Type@{b}}
    {Γ : Ctx B} {A U : Ty B}
  : Proper (TmEq@{b e _} ==> TmEq@{b e _}) (@tm_fst B Γ A U).
Proof. intros t u H. exact (tm_eq_fst H). Defined.

(** Second projection respects beta/eta equality. *)

(** 第二投影保持 βη 相等。 *)

Global Instance tm_snd_proper@{b e +} {B : Type@{b}}
    {Γ : Ctx B} {A U : Ty B}
  : Proper (TmEq@{b e _} ==> TmEq@{b e _}) (@tm_snd B Γ A U).
Proof. intros t u H. exact (tm_eq_snd H). Defined.

(** Abstraction respects equality of open bodies. *)

(** 抽象保持开放项体的相等。 *)

Global Instance tm_lam_proper@{b e +} {B : Type@{b}}
    {Γ : Ctx B} {A U : Ty B}
  : Proper (TmEq@{b e _} ==> TmEq@{b e _}) (@tm_lam B Γ A U).
Proof. intros t u H. exact (tm_eq_lam H). Defined.

(** Application respects equality of its function and argument. *)

(** 应用保持函数及参数的相等。 *)

Global Instance tm_app_proper@{b e +} {B : Type@{b}}
    {Γ : Ctx B} {A U : Ty B}
  : Proper (TmEq@{b e _} ==> TmEq@{b e _} ==> TmEq@{b e _})
      (@tm_app B Γ A U).
Proof. intros t t' H u u' K. exact (tm_eq_app H K). Defined.

(** Renaming respects beta/eta term equality and raw pointwise renaming
    equality simultaneously. *)

(** 重命名同时保持项的 βη 相等与原始重命名的逐点相等。 *)

Global Instance rename_tm_proper@{b e +} {B : Type@{b}}
    {Γ Δ : Ctx B} {A : Ty B}
  : Proper (TmEq@{b e _} ==> RenEq ==> TmEq@{b e _})
      (λ t ρ, @rename B Γ A t Δ ρ).
Proof.
  intros t u H ρ τ K. transitivity (u⟨ρ⟩).
  - apply tm_eq_rename. exact H.
  - apply tm_eq_of_eq. now apply rename_ext.
Defined.

(** Substitution respects beta/eta equality of both its term and assignments. *)

(** 替换同时保持项与各赋值的 βη 相等。 *)

Global Instance subst_tm_proper@{b e +} {B : Type@{b}}
    {Γ Δ : Ctx B} {A : Ty B}
  : Proper (TmEq@{b e _} ==> SubTmEq@{b e _} ==> TmEq@{b e _})
      (λ t σ, @subst B Γ A t Δ σ).
Proof.
  intros t u H σ τ K. transitivity (u[σ]).
  - apply tm_eq_subst. exact H.
  - now apply subst_tm_ext.
Defined.

(** Composition of substitutions respects both pointwise beta/eta relations. *)

(** 替换复合保持两侧的逐点 βη 相等。 *)

Global Instance sub_comp_tm_proper@{b e +} {B : Type@{b}}
    {Γ Δ Θ : Ctx B}
  : Proper
      (SubTmEq@{b e _} ==> SubTmEq@{b e _} ==> SubTmEq@{b e _})
      (@sub_comp B Γ Δ Θ).
Proof.
  intros σ σ' H τ τ' K A x. apply subst_tm_proper; [apply H | exact K].
Defined.

(** Extension respects beta/eta equality of the old assignments and new term. *)

(** 扩张保持旧赋值与新增项的 βη 相等。 *)

Global Instance sub_extend_tm_proper@{b e +} {B : Type@{b}}
    {Γ Δ : Ctx B} {A : Ty B}
  : Proper (SubTmEq@{b e _} ==> TmEq@{b e _} ==> SubTmEq@{b e _})
      (@sub_extend B Γ Δ A).
Proof.
  intros σ τ H t u K U [x | x]; cbn.
  - apply H.
  - destruct x. exact K.
Defined.

(** Replacing one variable respects beta/eta equality of the replacement. *)

(** 单变量代入保持所代入项的 βη 相等。 *)

Global Instance sub_single_tm_proper@{b e +} {B : Type@{b}}
    {Γ : Ctx B} {A : Ty B}
  : Proper (TmEq@{b e _} ==> SubTmEq@{b e _}) (@sub_single B Γ A).
Proof.
  intros t u H. unfold sub_single. apply sub_extend_tm_proper;
    [reflexivity | exact H].
Defined.
