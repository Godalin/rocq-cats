(** Simple types generated by base labels, unit, products and functions. *)

(** 由基类型标签、单位、积与函数生成的简单类型。 *)

Inductive Ty (B : Type)
  : Type
  :=| ty_base : B → Ty B
    | ty_unit : Ty B
    | ty_prod : Ty B → Ty B → Ty B
    | ty_arr : Ty B → Ty B → Ty B.

Arguments ty_base {_} _.
Arguments ty_unit {_}.
Arguments ty_prod {_} _ _.
Arguments ty_arr {_} _ _.
Bind Scope stlc_ty_scope with Ty.
Notation "'⊤'" := ty_unit : stlc_ty_scope.
Infix "×" := ty_prod (at level 41, right associativity) : stlc_ty_scope.
Infix "⇒" := ty_arr (at level 50, no associativity) : stlc_ty_scope.

(** Ordered contexts with the most recent variable on the right. *)

(** 有序上下文，最新变量位于右端。 *)

Inductive Ctx (B : Type)
  : Type
  :=| ctx_empty : Ctx B
    | ctx_snoc : Ctx B → Ty B → Ctx B.

Arguments ctx_empty {_}.
Arguments ctx_snoc {_} _ _.
Bind Scope stlc_ctx_scope with Ctx.
Notation "'∅'" := ctx_empty : stlc_ctx_scope.
Infix "▻" := ctx_snoc (at level 40, left associativity) : stlc_ctx_scope.
Local Open Scope stlc_ctx_scope.

(** A newly bound variable at its declared type. This small indexed marker
    carries no equality proof to be compared or transported. *)

(** 在声明类型处新绑定的小变量标记，不携带需要比较或运输的相等证明。 *)

Inductive NewVar {B : Type} (A : Ty B)
  : Ty B → Set
  :=| new_var : NewVar A A.

Arguments new_var {_ _}.

(** Typed de Bruijn variables: an older variable or the newest marker.
    Recursive context structure makes lifting ordinary sum elimination. *)

(** 带类型的 de Bruijn 变量：旧变量或最新标记。递归上下文结构使提升可直接按和
    类型消去。 *)

Fixpoint Var {B : Type} (Γ : Ctx B) (A : Ty B)
  : Set
  := match Γ with
  | ctx_empty => Empty_set
  | ctx_snoc Δ U => Var Δ A + NewVar U A
  end.

(** The most recent variable of an extended context. *)

(** 扩张上下文中的最新变量。 *)

Definition var_zero {B : Type} {Γ : Ctx B} {A : Ty B}
  : Var (Γ ▻ A) A
  := inr new_var.

(** Include an older variable in an extended context. *)

(** 将旧变量嵌入扩张上下文。 *)

Definition var_succ {B : Type} {Γ : Ctx B} {A U : Ty B} (x : Var Γ A)
  : Var (Γ ▻ U) A
  := inl x.

Notation "'𝟘'" := var_zero : stlc_var_scope.
Notation "'↑v' x" := (var_succ x) (at level 35) : stlc_var_scope.

(** Terms indexed by their context and type. Abstraction requires its body
    in the context extended by the input type. Application requires matching
    function and argument types, and variables must belong to the context. *)

(** 以所在上下文和类型索引的项。抽象要求项体位于按输入类型扩张的上下文；
    应用要求函数与实参类型匹配，变量必须属于当前上下文。 *)

Inductive Tm {B : Type}
  : Ctx B → Ty B → Type
  :=| tm_var {Γ A} : Var Γ A → Tm Γ A
    | tm_unit {Γ} : Tm Γ ty_unit
    | tm_pair {Γ A U} : Tm Γ A → Tm Γ U → Tm Γ (ty_prod A U)
    | tm_fst {Γ A U} : Tm Γ (ty_prod A U) → Tm Γ A
    | tm_snd {Γ A U} : Tm Γ (ty_prod A U) → Tm Γ U
    | tm_lam {Γ A U} : Tm (Γ ▻ A) U → Tm Γ (ty_arr A U)
    | tm_app {Γ A U} : Tm Γ (ty_arr A U) → Tm Γ A → Tm Γ U.

Arguments tm_var {_ _ _} _.
Arguments tm_unit {_ _}.
Arguments tm_pair {_ _ _ _} _ _.
Arguments tm_fst {_ _ _ _} _.
Arguments tm_snd {_ _ _ _} _.
Arguments tm_lam {_ _ _ _} _.
Arguments tm_app {_ _ _ _} _ _.
Bind Scope stlc_tm_scope with Tm.
Notation "'#' x" := (tm_var x) (at level 35) : stlc_tm_scope.
Notation "'⋆'" := tm_unit : stlc_tm_scope.
Notation "'⟨' t ',' u '⟩'" := (tm_pair t u) : stlc_tm_scope.
Notation "'π₁' t" := (tm_fst t) (at level 35) : stlc_tm_scope.
Notation "'π₂' t" := (tm_snd t) (at level 35) : stlc_tm_scope.
Notation "'ƛ' t" := (tm_lam t) (at level 35) : stlc_tm_scope.
Infix "·" := tm_app (at level 20, left associativity) : stlc_tm_scope.

(** ** Reading small terms

    [ƛ (# 𝟘)] has type [Tm Γ (A ⇒ A)]: its body returns the just-bound
    input. [⟨# 𝟘, # 𝟘⟩] has type [Tm (∅ ▻ A) (A × A)]: the context has
    one input even though the body uses it twice. Weakening and duplication
    are allowed; this is ordinary STLC, without linear usage restrictions.

    [ƛ (ƛ (# (↑v 𝟘)))] has type [Tm Γ (A ⇒ (U ⇒ A))]. In the inner
    body the newest variable is the [U]-input, so the older position selects
    the [A]-input. Binding positions replace names, while renaming and
    substitution must still account for those positions under each binder.
    Nested function types use explicit parentheses in this notation. *)

(** ** 阅读小型项

    [ƛ (# 𝟘)] 具有类型 [Tm Γ (A ⇒ A)]：项体返回刚绑定的输入。
    [⟨# 𝟘, # 𝟘⟩] 具有类型 [Tm (∅ ▻ A) (A × A)]：虽然项体使用变量两次，
    上下文仍只有一个输入。这里允许弱化与复制，是通常的 STLC，没有线性使用
    限制。

    [ƛ (ƛ (# (↑v 𝟘)))] 具有类型 [Tm Γ (A ⇒ (U ⇒ A))]。在内层项体中，
    最新变量是 [U] 输入，因此旧位置选取 [A] 输入。绑定位置代替变量名，
    但重命名与替换进入每个绑定时仍须调整这些位置。此记法要求嵌套函数类型
    显式加括号。 *)
