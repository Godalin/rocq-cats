From Cats.Set Require Export
  Morphism.

(** * Generated Equivalence Relations *)

(** * 生成等价关系 *)

(** Retain finite derivations of the equivalence relation generated by [R].
    Intermediate elements and relation witnesses remain computational data. *)

(** 保留 [R] 所生成等价关系的有限推导；中间元素及关系见证仍为计算数据。 *)

Inductive EquivClosure {A : Type} (R : crelation A)
  : crelation A
  :=| closure_refl (x : A) : EquivClosure R x x
    | closure_step {x y : A} : R x y → EquivClosure R x y
    | closure_sym {x y : A}
        : EquivClosure R x y → EquivClosure R y x
    | closure_trans {x y z : A}
        : EquivClosure R x y → EquivClosure R y z → EquivClosure R x z.

Arguments closure_refl {_ _} _.
Arguments closure_step {_ _ _ _} _.
Arguments closure_sym {_ _ _ _} _.
Arguments closure_trans {_ _ _ _ _} _ _.

Notation "R '^≈'" := (EquivClosure R)
  (at level 20) : set_scope.

(** The closure constructors supply the specified equivalence laws. *)

(** 闭包构造器给出指定等价律。 *)

Global Instance EquivClosure_Equivalence {A : Type} (R : crelation A)
  : Equivalence (R^≈) | 100.
Proof.
  split; [exact closure_refl | exact (λ x y, closure_sym) |
    exact (λ x y z, closure_trans)].
Defined.

(** A function preserving the generators preserves their entire equivalence
    closure into any specified equivalence relation. *)

(** 保持生成元的函数将整个等价闭包保持到任意指定等价关系中。 *)

Definition equiv_closure_preserves {A B : Type}
    {R : crelation A} {S : crelation B} `{HS : !Equivalence S}
    (f : A → B) (Hf : ∀ x y, R x y → S (f x) (f y))
    {x y : A} (H : (R^≈) x y)
  : S (f x) (f y).
Proof.
  induction H.
  - reflexivity.
  - apply Hf. assumption.
  - symmetry. assumption.
  - etransitivity; eassumption.
Defined.

(** The closure is the least equivalence relation containing its generators,
    expressed by Type-valued witness transformations. *)

(** 闭包是包含生成元的最小等价关系，以 Type 值见证转换表达。 *)

Definition equiv_closure_universal {A : Type} (R S : crelation A)
    `{HS : !Equivalence S}
  : (∀ x y, R x y → S x y) ↔ (∀ x y, (R^≈) x y → S x y).
Proof.
  split.
  - intros H x y p. exact (equiv_closure_preserves (λ x, x) H p).
  - intros H x y p. exact (H x y (closure_step p)).
Defined.

(** Equip a carrier with the generated equivalence, without quotienting its
    native elements. The inferred witness universe contains intermediates. *)

(** 为载体配置生成等价，不对原生元素取商；推导出的见证宇宙包含中间元素。 *)

Program Definition GeneratedS (A : Type) (R : crelation A)
  : SetC
  :=
  {|carrier := A
  ; carrier_equiv := R^≈
  |}.

(** A generator-preserving function descends transparently to the generated
    setoid; only its respectfulness proof changes. *)

(** 保持生成元的函数透明地下降到生成广集，只改变其保相等证明。 *)

Program Definition generated_resp {A : Type} {R : crelation A} {Z : SetC}
    (f : A → Z) (Hf : ∀ x y, R x y → f x ≈S f y)
  : GeneratedS A R →r Z
  :=
  {|func := f
  |}.
Next Obligation.
  intros x y H. exact (equiv_closure_preserves f Hf H).
Defined.
