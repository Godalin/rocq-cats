From Minks Require Import all.

Set Universe Polymorphism.

(** Bidirectional inference for three overlapping relative exports.
    Each interface uses the registrations generated by its export. *)

Module Overlap.
Minks.Mixin HasA (X : Type) := { a : X }.
Minks.Mixin HasB (X : Type) := { b : X }.
Minks.Mixin HasC (X : Type)
  extends HasB X
  := { c : b = b }.
Minks.Struct AB
  extends Type
  with  first : HasA, middle : HasB
  exports HasAB [carrier].
Minks.Struct BC
  extends Type
  with  middle : HasB, last : HasC
  exports HasBC [carrier].
Minks.Struct ABC
  extends AB, BC
  exports HasABC [carrier].

(** A projection followed by its own constructor would ask for the very
    field being projected. Cut that path separately for each export. *)

Section Composition.
Section Independent.
Context (X : Type) `{A : !HasA X} `{B : !HasB X} `{C : !HasC X}.
Definition from_atoms : HasABC X := _.
Example exact_a : HasABC_first from_atoms = A := eq_refl.
Example exact_b : HasABC_middle from_atoms = B := eq_refl.
Example exact_c : HasABC_last from_atoms = C := eq_refl.
Fail Definition no_pack : ABC := X.
End Independent.

Section Projection.
Context (X : Type) `{G : !HasABC X}.
Definition ab : HasAB X := _.
Example extract_a : HasAB_first ab = HasABC_first G := eq_refl.
End Projection.

Section Extend.
Context (X : Type) `{L : !HasAB X} `{C : !@HasC X (HasAB_middle L)}.
Definition extended : HasABC X := _.
Example extend_exact : extended =
    MakeHasABC X (HasAB_middle L) (HasAB_first L) C := eq_refl.
End Extend.

Section Join.
Context (X : Type) `{L : !HasAB X} `{R : !HasBC X}.
Definition joined : HasABC X := _.
Example join_a : HasABC_first joined = HasAB_first L := eq_refl.
Example join_b : HasABC_middle joined = HasBC_middle R := eq_refl.
Example join_c : HasABC_last joined = HasBC_last R := eq_refl.
Fail Definition use_other_middle : @HasC X (HasAB_middle L) := HasBC_last R.
End Join.

(** When both inputs come from the same middle witness, both views are
    recovered by conversion, including the dependent last field. *)

Section SharedMiddle.
Context (X : Type) (A : HasA X) (B : HasB X) (C : @HasC X B).
Example shared_join
  : @joined X (MakeHasAB X A B) (MakeHasBC X B C) = MakeHasABC X B A C
  := eq_refl.
End SharedMiddle.

Section Missing.
Context (X : Type) `{L : !HasAB X}.
Timeout 3 Fail Definition no_c : HasABC X := _.
End Missing.

(** An extra interface-to-interface instance bypasses the per-export cuts.
    This shortcut is local to the experiment. *)
Section LargerInterfaceDetour.
#[local] Instance ab_from_abc {X : Type} `{G : !HasABC X} : HasAB X
  := MakeHasAB X (HasABC_first G) (HasABC_middle G).

Section MissingFirst.
Context (X : Type) `{B : !HasB X} `{C : !HasC X}.

(** Before adding the following cut, this command times out:
    [Timeout 2 Definition missing_first : HasA X := _.]
    The trace repeats [HasAB_first], [ab_from_abc], [MakeHasABC]. *)
#[local] Hint Cut [_* ab_from_abc MakeHasABC] : typeclass_instances.
Timeout 3 Fail Definition missing_first : HasA X := _.

Context `{G : !HasABC X}.
Definition first_from_known : HasA X := _.
Example kept_first : first_from_known = HasABC_first G := eq_refl.
End MissingFirst.
End LargerInterfaceDetour.
End Composition.
End Overlap.

(** Two overlapping exports constrain the same pair of component witnesses. *)

Module JointDependency.
Minks.Mixin HasB (X : Type) := { b : X }.
Minks.Mixin HasC (X : Type) := { c : X }.
Minks.Mixin HasD (X : Type)
  extends HasB X, HasC X
  := { d : b = c }.
Minks.Mixin HasE (X : Type)
  extends HasB X, HasC X
  := { e : c = b }.

Minks.Struct BC
  extends Type
  with  left : HasB, right : HasC.
Minks.Struct BCD
  extends BC
  with  jointD : HasD
  exports HasBCD [carrier].
Minks.Struct BCE
  extends BC
  with  jointE : HasE
  exports HasBCE [carrier].
Minks.Struct BCDE
  extends BCD, BCE
  exports HasBCDE [carrier].

Section Candidates.
Context (X : Type) (B0 B1 : HasB X) (C0 C1 : HasC X).

(** Each interface alone prefers a pair the other cannot supply.
    The joint search must reconsider that choice in either search order. *)

Section Backtrack.
Context `{D00 : !@HasD X B0 C0} `{E00 : !@HasE X B0 C0}
  `{D10 : !@HasD X B1 C0} `{E01 : !@HasE X B0 C1}.

Example preferred_d : (_ : HasBCD X) = MakeHasBCD X B1 C0 D10 := eq_refl.
Example preferred_e : (_ : HasBCE X) = MakeHasBCE X B0 C1 E01 := eq_refl.
Timeout 3 Definition assembled : HasBCDE X := _.
Example selected_b : HasBCDE_left assembled = B0 := eq_refl.
Example selected_c : HasBCDE_right assembled = C0 := eq_refl.
Example selected_d : HasBCDE_jointD assembled = D00 := eq_refl.
Example selected_e : HasBCDE_jointE assembled = E00 := eq_refl.
End Backtrack.

(** Every B and every C occurs on both sides. The D witnesses lie on the
    diagonal and the E witnesses off it, so no pair works for both. *)

Section Incompatible.
Context `{D00 : !@HasD X B0 C0} `{D11 : !@HasD X B1 C1}
  `{E01 : !@HasE X B0 C1} `{E10 : !@HasE X B1 C0}.

Definition d_alone : HasBCD X := _.
Definition e_alone : HasBCE X := _.
Timeout 3 Fail Definition no_common_pair : HasBCDE X := _.
End Incompatible.
End Candidates.
End JointDependency.

(** Two slots with the same class type require an explicit choice. A plain
    constructor instance can silently fill both slots with one witness. *)

Module Repeated.
Import Overlap.
Minks.Struct Two
  extends Type
  with  leftPoint : HasA, rightPoint : HasA
  exports TwoChoices [carrier].

Section Selection.
Context (X : Type) `{P : !HasA X}.
Timeout 3 Fail Definition ambiguous : TwoChoices X := _.
Example explicit_right (Q : HasA X)
  : TwoChoices_rightPoint (MakeTwoChoices X P Q) = Q
  := eq_refl.
End Selection.
End Repeated.

Module RecursiveAssembly.
Minks.Mixin Choice (A : Type) := { chosen : A }.
Minks.Struct Pack
  extends Type
  with  choice : Choice
  exports Choices [carrier].
Timeout 3 Fail Definition bare : Choices unit := _.
(** The same constructor can be needed at successively smaller indices. *)
#[local] Instance diagonal_choice {X : Type} `{S : !Choices X}
  : Choice (X * X) :=
  let x := @chosen X (Choices_choice S) in Build_Choice _ (x, x).

Section SmallerInputs.
Context (X : Type).
Timeout 3 Fail Definition missing_leaf : Choices ((X * X) * (X * X)) := _.
Context `{P : !Choice X}.
Definition nested : Choices ((X * X) * (X * X)) := _.
Example selected_leaf :
  let x := @chosen X P in
  @chosen _ (Choices_choice nested) = ((x, x), (x, x)) := eq_refl.
End SmallerInputs.
End RecursiveAssembly.

From MinksExamples Require Import Algebra.

Module RelativeGroup.

Section Assembly.
Context (M : Monoid).
Timeout 3 Fail Definition no_inverse : IsGroup M := _.
Context `{I : !HasInverse M}.
Definition relative : IsGroup M := _.
Example exact_inverse : IsGroup_hasInverse relative = I := eq_refl.
Fail Definition automatic_group : Group := M.
Definition packed : Group := GroupOfIsGroup M relative.
End Assembly.
End RelativeGroup.
